const T = (tier: number, range: string, repLevel: number, label: string, polyBudget: string, scaleBoost: number, glowIntensity: number, visualChanges: string[]): BuildingTier =>
  ({ tier, range, repLevel, label, polyBudget, scaleBoost, glowIntensity, visualChanges });

export function outAt(b: BuildingSpec, level: number): number {
  return b.baseOutput * level * Math.pow(2, Math.floor(level / 10));
}
export function costAt(b: BuildingSpec, level: number): number {
  return Math.round(b.baseCost * Math.pow(1.15, level - 1));
}
export function fmtBig(n: number): string {
  if (n >= 1e9) return (n / 1e9).toFixed(1) + "B";
  if (n >= 1e6) return (n / 1e6).toFixed(1) + "M";
  if (n >= 1e4) return (n / 1e3).toFixed(1) + "K";
  return Math.round(n).toLocaleString("en-US");
}

