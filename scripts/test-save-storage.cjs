const assert=require('node:assert/strict');
const {load}=require('./load-game.cjs');
const S=load('src/lib/save-storage.ts'), G=load('src/lib/game.ts');
const data=new Map();
let quota=false;
const storage={getItem:k=>data.get(k)??null,setItem(k,v){if(quota)throw Error('quota');data.set(k,v)},removeItem:k=>data.delete(k)};
const first=G.initialGame();S.writeSnapshot(storage,first);
S.writeSnapshot(storage,{...first,cash:900});
assert.equal(S.saveCandidates(storage)[0].state.cash,900);
data.set(S.SAVE_KEY,'broken');
assert.equal(S.saveCandidates(storage)[0].recovered,true);
assert.equal(S.saveCandidates(storage)[0].state.cash,first.cash);
S.writeSnapshot(storage,{...first,cash:700});
assert.equal(JSON.parse(data.get(S.SAVE_BACKUP_KEY)).state.cash,first.cash,'corrupt primary must not replace good backup');
quota=true;
assert.throws(()=>S.writeSnapshot(storage,{...first,cash:400}));
assert.equal(S.saveCandidates(storage)[0].state.cash,700,'quota failure preserves latest durable primary');
assert.throws(()=>S.writeSnapshot(storage,{version:999}));
console.log('PASS save migration, corrupt-primary recovery, backup preservation, quota failure and invalid-state rejection');

data.clear(); quota=false;
const legacy=JSON.stringify({...first,cash:1037,oil:318,lastSavedAt:Date.now()});
data.set(S.LEGACY_SAVE_KEY,legacy);
const candidate=S.saveCandidates(storage)[0];
assert.equal(candidate.recovered,false);
const restored=G.hydrateGame(candidate.state);
assert.ok(restored);
assert.equal(restored.game.cash,1037);
assert.equal(restored.game.oil,318);
assert.ok(!restored.game.opening,'historical ports skip the new installation reward');
S.writeSnapshot(storage,restored.game);
assert.equal(data.get(S.LEGACY_SAVE_KEY),legacy,'migration preserves exact source bytes');
assert.equal(JSON.parse(data.get(S.SAVE_KEY)).version,2);
S.writeSnapshot(storage,{...restored.game,cash:820});
assert.equal(S.saveCandidates(storage)[0].state.cash,820);
assert.equal(S.saveCandidates(storage).length,2);
S.resetSaveSlots(storage);
assert.deepEqual(S.saveCandidates(storage),[],'reset cannot resurrect v1 before autosave');
assert.equal(data.get(S.LEGACY_SAVE_KEY),legacy);
data.clear(); data.set(S.LEGACY_BACKUP_KEY,legacy);
assert.equal(S.saveCandidates(storage)[0].recovered,true);
quota=true;
assert.throws(()=>S.writeSnapshot(storage,first)); quota=false;
assert.equal(data.get(S.LEGACY_BACKUP_KEY),legacy);
assert.equal(S.saveCandidates(storage)[0].state.cash,1037);
data.set(S.SAVE_KEY,JSON.stringify({version:9,state:first}));
const future=data.get(S.SAVE_KEY);
assert.throws(()=>S.saveCandidates(storage),S.SaveFormatError);
assert.throws(()=>S.writeSnapshot(storage,first),S.SaveFormatError);
assert.equal(data.get(S.SAVE_KEY),future);
data.clear(); data.set(S.SAVE_KEY,'broken');
assert.throws(()=>S.saveCandidates(storage),S.SaveFormatError);
const indexed={...storage,get length(){return data.size},key:i=>[...data.keys()][i]??null};
data.clear(); data.set('hormuz-game-v3','future bytes');
assert.throws(()=>S.saveCandidates(indexed),e=>e.reason==='newer');
assert.throws(()=>S.writeSnapshot(indexed,first),e=>e.reason==='newer');
assert.deepEqual(S.localSaveArchive(indexed),{'hormuz-game-v3':'future bytes'});
data.clear(); data.set(S.SAVE_KEY,JSON.stringify({version:2,state:{...first,version:3}}));
assert.throws(()=>S.saveCandidates(storage),e=>e.reason==='newer');
console.log('PASS v1 to v2 migration, immutable original, backup fallback, reset, interrupted migration and future schema protection');
